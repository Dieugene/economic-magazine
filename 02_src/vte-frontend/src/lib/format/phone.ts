// Маска ввода телефона для российского формата +7 (XXX) XXX-XX-XX.
// Пользователь может начать с "+", "7", "8" или сразу с цифр номера —
// функция нормализует и форматирует значение в маску по ходу ввода.
// Любые нецифровые символы отбрасываются.
//
// Примеры:
//   ""               → ""
//   "8"              → "+7"
//   "+"              → "+7"
//   "+7"             → "+7"
//   "9"              → "+7 (9"
//   "899"            → "+7 (9"   — "8" трактуется как код страны
//   "8999"           → "+7 (999"
//   "89991"          → "+7 (999) 1"
//   "89991234567"    → "+7 (999) 123-45-67"
//   "79991234567"    → "+7 (999) 123-45-67"
//   "+79991234567"   → "+7 (999) 123-45-67"
//   "9991234567"     → "+7 (999) 123-45-67"
//   "abc"            → ""
//   Лишние цифры за пределами 10-значного номера отбрасываются.
export function formatPhoneMask(input: string): string {
  // Если пользователь не начал ввод (нет ни цифры, ни "+") — оставляем пусто,
  // чтобы placeholder работал.
  if (!/[\d+]/.test(input)) return "";

  // Извлекаем только цифры.
  let digits = input.replace(/\D/g, "");
  // Первая 7/8 — это код страны, мы его принудительно превращаем в "+7" префикс.
  if (digits[0] === "8" || digits[0] === "7") digits = digits.slice(1);
  // Ограничиваем 10 цифрами (без кода страны).
  digits = digits.slice(0, 10);

  let result = "+7";
  if (digits.length > 0) result += " (" + digits.slice(0, 3);
  if (digits.length >= 3) result += ")";
  if (digits.length > 3) result += " " + digits.slice(3, 6);
  if (digits.length > 6) result += "-" + digits.slice(6, 8);
  if (digits.length > 8) result += "-" + digits.slice(8, 10);
  return result;
}
